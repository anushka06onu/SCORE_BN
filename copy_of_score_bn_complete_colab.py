# ------------------------------------------------------------
# Deep-learning model builder
# ------------------------------------------------------------

def make_deep_model(kind):

    inputs = layers.Input(
        shape=(MAX_LEN,),
        dtype='int64',
        name='token_ids'
    )

    # CNN does not support the embedding mask in this architecture.
    use_mask = kind != 'CNN'

    x = layers.Embedding(
        input_dim=len(vectorizer.get_vocabulary()),
        output_dim=EMBED_DIM,
        mask_zero=use_mask,
        name='embedding'
    )(inputs)

    if kind == 'CNN':

        x = layers.Conv1D(
            filters=128,
            kernel_size=3,
            activation='relu',
            name='convolution'
        )(x)

        x = layers.GlobalMaxPooling1D(
            name='global_max_pooling'
        )(x)

    elif kind == 'BiLSTM':

        x = layers.Bidirectional(
            layers.LSTM(
                units=64,
                dropout=0.20
            ),
            name='bidirectional_lstm'
        )(x)

    elif kind == 'BiGRU':

        x = layers.Bidirectional(
            layers.GRU(
                units=64,
                dropout=0.20
            ),
            name='bidirectional_gru'
        )(x)

    else:
        raise ValueError(
            "Model kind must be CNN, BiLSTM, or BiGRU."
        )

    x = layers.Dropout(
        rate=0.35,
        name='dropout'
    )(x)

    outputs = layers.Dense(
        units=4,
        activation='softmax',
        name='severity_output'
    )(x)

    model = Model(
        inputs=inputs,
        outputs=outputs,
        name=kind
    )

    model.compile(
        optimizer=tf.keras.optimizers.Adam(
            learning_rate=0.001
        ),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    return model


