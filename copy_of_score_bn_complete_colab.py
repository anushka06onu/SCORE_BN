def clean_classical(text):

    text = unicodedata.normalize(
        "NFKC",
        str(text)
    )

    text = re.sub(
        r"https?://\S+|www\.\S+",
        " URL ",
        text
    )

    text = re.sub(
        r"@[A-Za-z0-9_]+",
        " USER ",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    ).strip().lower()

    return text


def evaluate_probabilities(
    model_name,
    stage,
    true_labels,
    probabilities,
    notes=""
):

    probabilities = np.asarray(
        probabilities
    )

    predictions = probabilities.argmax(
        axis=1
    )

    precision, recall, f1, _ = (
        precision_recall_fscore_support(
            true_labels,
            predictions,
            average="macro",
            zero_division=0
        )
    )

    try:

        auc = roc_auc_score(
            true_labels,
            probabilities,
            multi_class="ovr",
            average="macro"
        )

    except Exception:

        auc = np.nan

    add_result(
        model=model_name,
        stage=stage,
        accuracy=accuracy_score(
            true_labels,
            predictions
        ),
        macro_precision=precision,
        macro_recall=recall,
        macro_f1=f1,
        roc_auc_ovr=auc,
        notes=notes
    )


