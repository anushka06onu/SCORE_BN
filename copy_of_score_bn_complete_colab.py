def normalize_for_dedup(text):
    text = unicodedata.normalize('NFKC', str(text))
    text = re.sub(r'https?://\S+|www\.\S+', ' URL ', text)
    text = re.sub(r'\s+', ' ', text).strip().lower()
    return text

