class PairedDataset(TorchDataset):

    def __init__(
        self,
        frame,
        tokenizer,
        max_length=128
    ):

        self.frame = (
            frame
            .copy()
            .reset_index(drop=True)
        )

        self.tokenizer = tokenizer
        self.max_length = max_length

    def __len__(self):

        return len(self.frame)

    def __getitem__(self, index):

        row = self.frame.iloc[index]

        original_encoding = self.tokenizer(
            str(row['text']),
            truncation=True,
            max_length=self.max_length
        )

        romanized_encoding = self.tokenizer(
            str(row['view_text']),
            truncation=True,
            max_length=self.max_length
        )

        return {
            'original': original_encoding,
            'view': romanized_encoding,
            'label': int(row['label'])
        }


def paired_collate(batch):

    original_batch = tokenizer.pad(
        [
            item['original']
            for item in batch
        ],
        return_tensors='pt'
    )

    view_batch = tokenizer.pad(
        [
            item['view']
            for item in batch
        ],
        return_tensors='pt'
    )

    labels = torch.tensor(
        [
            item['label']
            for item in batch
        ],
        dtype=torch.long
    )

    return {
        'original': original_batch,
        'view': view_batch,
        'labels': labels
    }

