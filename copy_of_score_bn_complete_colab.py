def validate_score_bn(
    model,
    validation_loader
):

    model.eval()

    validation_losses = []
    all_labels = []
    all_predictions = []

    with torch.no_grad():

        for batch in validation_loader:

            original = {
                key: value.to(device)
                for key, value
                in batch[
                    'original'
                ].items()
            }

            view = {
                key: value.to(device)
                for key, value
                in batch[
                    'view'
                ].items()
            }

            labels = batch[
                'labels'
            ].to(device)

            with torch.autocast(
                device_type='cuda',
                dtype=torch.float16,
                enabled=torch.cuda.is_available()
            ):

                original_logits, view_logits = (
                    model(
                        original,
                        view
                    )
                )

                loss, _ = score_bn_loss(
                    original_logits,
                    view_logits,
                    labels,
                    LAMBDA_ORDINAL,
                    LAMBDA_CONSISTENCY,
                    LAMBDA_UNDER
                )

            validation_losses.append(
                loss.item()
            )

            predictions = (
                original_logits
                .argmax(dim=-1)
            )

            all_labels.extend(
                labels
                .cpu()
                .numpy()
            )

            all_predictions.extend(
                predictions
                .cpu()
                .numpy()
            )

    precision, recall, macro_f1, _ = (
        precision_recall_fscore_support(
            all_labels,
            all_predictions,
            average='macro',
            zero_division=0
        )
    )

    return {
        'validation_loss': float(
            np.mean(
                validation_losses
            )
        ),

        'validation_accuracy': (
            accuracy_score(
                all_labels,
                all_predictions
            )
        ),

        'validation_precision': precision,
        'validation_recall': recall,
        'validation_macro_f1': macro_f1
    }

