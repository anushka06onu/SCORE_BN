# 7. SCORE-BN model
# ------------------------------------------------------------

class ScoreBN(nn.Module):

    def __init__(
        self,
        model_name,
        number_of_labels=4,
        dropout=0.2
    ):

        super().__init__()

        self.encoder = AutoModel.from_pretrained(
            model_name
        )

        # Reduce GPU-memory use
        if hasattr(
            self.encoder,
            'gradient_checkpointing_enable'
        ):
            self.encoder.gradient_checkpointing_enable()

        self.dropout = nn.Dropout(
            dropout
        )

        self.classifier = nn.Linear(
            self.encoder.config.hidden_size,
            number_of_labels
        )

    def encode_one(self, encoded_batch):

        encoder_output = self.encoder(
            **encoded_batch
        )

        cls_representation = (
            encoder_output
            .last_hidden_state[:, 0, :]
        )

        cls_representation = (
            self.dropout(
                cls_representation
            )
        )

        return self.classifier(
            cls_representation
        )

    def forward(
        self,
        original_batch,
        view_batch=None
    ):

        original_logits = self.encode_one(
            original_batch
        )

        view_logits = None

        if view_batch is not None:

            view_logits = self.encode_one(
                view_batch
            )

        return (
            original_logits,
            view_logits
        )

# ------------------------------------------------------------
# 8. SCORE-BN loss
# ------------------------------------------------------------

def score_bn_loss(
    original_logits,
    view_logits,
    labels,
    lambda_ordinal=0.5,
    lambda_consistency=0.5,
    lambda_under=0.3
):

    # Standard four-class classification loss
    classification_loss = (
        F.cross_entropy(
            original_logits,
            labels
        )
        +
        F.cross_entropy(
            view_logits,
            labels
        )
    ) / 2

    original_probabilities = F.softmax(
        original_logits,
        dim=-1
    )

    view_probabilities = F.softmax(
        view_logits,
        dim=-1
    )

    # --------------------------------------------------------
    # Ordinal cumulative-target loss
    # --------------------------------------------------------

    thresholds = torch.arange(
        3,
        device=labels.device
    ).unsqueeze(0)

    ordinal_targets = (
        labels.unsqueeze(1)
        > thresholds
    ).float()

    original_cumulative = torch.stack(
        [
            original_probabilities[
                :, 1:
            ].sum(dim=-1),

            original_probabilities[
                :, 2:
            ].sum(dim=-1),

            original_probabilities[
                :, 3:
            ].sum(dim=-1)
        ],
        dim=1
    ).clamp(
        1e-6,
        1 - 1e-6
    )

    view_cumulative = torch.stack(
        [
            view_probabilities[
                :, 1:
            ].sum(dim=-1),

            view_probabilities[
                :, 2:
            ].sum(dim=-1),

            view_probabilities[
                :, 3:
            ].sum(dim=-1)
        ],
        dim=1
    ).clamp(
        1e-6,
        1 - 1e-6
    )

    ordinal_loss = (
        F.binary_cross_entropy(
            original_cumulative,
            ordinal_targets
        )
        +
        F.binary_cross_entropy(
            view_cumulative,
            ordinal_targets
        )
    ) / 2

    # --------------------------------------------------------
    # Jensen-Shannon consistency loss
    # --------------------------------------------------------

    midpoint = (
        original_probabilities
        +
        view_probabilities
    ) / 2

    midpoint = midpoint.clamp(
        min=1e-8
    )

    consistency_loss = 0.5 * (
        F.kl_div(
            midpoint.log(),
            original_probabilities,
            reduction='batchmean'
        )
        +
        F.kl_div(
            midpoint.log(),
            view_probabilities,
            reduction='batchmean'
        )
    )

    # --------------------------------------------------------
    # Asymmetric under-prioritisation loss
    # --------------------------------------------------------

    severity_values = torch.arange(
        4,
        device=labels.device,
        dtype=torch.float32
    )

    original_expected_severity = (
        original_probabilities
        *
        severity_values
    ).sum(dim=-1)

    view_expected_severity = (
        view_probabilities
        *
        severity_values
    ).sum(dim=-1)

    under_prioritisation_loss = (
        F.relu(
            labels.float()
            -
            original_expected_severity
        ).pow(2)
        +
        F.relu(
            labels.float()
            -
            view_expected_severity
        ).pow(2)
    ).mean() / 2

    total_loss = (
        classification_loss
        +
        lambda_ordinal
        * ordinal_loss
        +
        lambda_consistency
        * consistency_loss
        +
        lambda_under
        * under_prioritisation_loss
    )

    components = {
        'classification': (
            classification_loss
            .detach()
            .item()
        ),

        'ordinal': (
            ordinal_loss
            .detach()
            .item()
        ),

        'consistency': (
            consistency_loss
            .detach()
            .item()
        ),

        'under': (
            under_prioritisation_loss
            .detach()
            .item()
        )
    }

    return total_loss, components

