def normalize_text(text):

    text = unicodedata.normalize(
        'NFKC',
        str(text)
    )

    text = re.sub(
        r'https?://\S+|www\.\S+',
        ' URL ',
        text
    )

    text = re.sub(
        r'@[A-Za-z0-9_]+',
        ' USER ',
        text
    )

    text = re.sub(
        r'\s+',
        ' ',
        text
    )

    return text.strip().lower()


def tokenize_text(text):

    return re.findall(
        r'[\u0980-\u09FFA-Za-z]+',
        str(text).lower()
    )


